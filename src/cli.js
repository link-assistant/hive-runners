const optionsByCommand = Object.fromEntries(
  Object.entries(commands).map(([name, [usage]]) => [
    name,
    Object.fromEntries(
      [...usage.matchAll(/--([a-z-]+)/g)].map(([, option]) => [
        option,
        { type: option === 'apply-infra' ? 'boolean' : 'string' },
      ])
    ),
  ])
);

export function cliReference() {
  return [
    '# Hive Runners CLI reference',
    '',
    'Generated by `hive-runners docs`. Command options use the long forms below.',
    'The default configuration is `hive-runners.lino`. Use `--json` for JSON command output.',
    '',
    ...Object.entries(commands).flatMap(([name, [syntax, description]]) => [
      `## ${name}`,
      '',
      description,
      '',
      '```text',
      `hive-runners ${name} ${syntax}`,
      '```',
      '',
    ]),
  ].join('\n');
}

function help() {
  return [
    'Usage: hive-runners <command> [options]',
    'Options: --json for JSON command output',
    '',
    ...Object.entries(commands).map(
      ([name, [syntax]]) => `  ${name} ${syntax}`
    ),
  ].join('\n');
}

async function githubCommand(command, options, { env, fetcher, run }) {
  const scope = match(options.scope, githubScope, 'GitHub scope');
  const client = githubClient(await githubToken(env, undefined, run), fetcher);
  if (command === 'github-runners') {
    return client.listRunners(scope);
  }
  if (command === 'github-labels') {
    requireValue(
      typeof options.labels === 'string',
      'Pass --labels with comma-separated custom labels'
    );
    return client.setLabels(
      scope,
      Number(options.id),
      options.labels === ''
        ? []
        : options.labels
            .split(',')
            .map((label) =>
              match(label, /^[A-Za-z0-9][A-Za-z0-9._-]{0,99}$/, 'label')
            )
    );
  }
  requireValue(
    !scope.includes('/'),
    'Runner group commands require an organization scope'
  );
  if (command === 'github-groups') {
    return client.listGroups(scope);
  }
  return client.ensureGroup(
    scope,
    options.name,
    (options.repositories ?? '').split(',').filter(Boolean)
  );
}

async function gitlabCommand(command, options, { env, fetcher }) {
  const client = gitlabClient(
    options.origin ?? 'https://gitlab.com',
    secret('HIVE_GITLAB_TOKEN', env),
    fetcher
  );
  if (command === 'gitlab-tag') {
    return client.configureRunner(Number(options.id), options.name);
  }
  const scope = match(options.scope, gitlabScope, 'GitLab scope');
  const kind = match(
    options.kind ?? 'project',
    /^(project|group)$/,
    'GitLab scope type'
  );
  if (command === 'gitlab-create') {
    return client.createRunner(scope, kind, options.name);
  }
  await client.privateScope(scope, kind);
  return client.listRunners(scope, kind);
}

function accountCommand(command, options, { env, fetcher }) {
  const account = runnerAccount(
    options.origin,
    secret('HIVE_ACCOUNT_KEY', env),
    {
      fetcher,
    }
  );
  if (command === 'account-offer') {
    return account.offer();
  }
  if (command === 'account-activate') {
    return account.offer().then((offer) =>
      account.activate(Number(options.minutes), {
        offer,
        maxCents:
          options['max-cents'] === undefined
            ? undefined
            : Number(options['max-cents']),
      })
    );
  }
  if (command === 'account-stop') {
    return account.stop();
  }
  return account.checkout(Number(options.cents), options['request-id']);
}

async function runConfigured(command, options, input, { env, fetcher, run }) {
  if (command === 'render') {
    return renderInfrastructure(input, options.directory ?? '.');
  }
  if (command === 'capacity') {
    return capacityPlan(input, options.shared?.split(','));
  }
  if (command === 'deploy') {
    return deploy(input, {
      directory: options.directory,
      inventory: options.inventory && (await readData(options.inventory)),
      apply: options['apply-infra'] ?? false,
      env,
      fetcher,
      run,
    });
  }
  if (command === 'proposal') {
    return propose(input, { base: options.base, branch: options.branch, run });
  }
  if (command === 'serve') {
    const { serve } = await import('./control/server.js');
    const server = await serve(input, { env });
    return `Hive Runners listening on port ${server.address().port}`;
  }
  const name = match(options.name, slug, 'provider name');
  requireValue(Object.hasOwn(input.providers, name), 'Provider not configured');
  return providerClient(input.providers[name], { env, fetcher }).list();
}

async function dispatch(command, options, dependencies) {
  if (command === 'docs') {
    if (!options.output) {
      return cliReference();
    }
    await writeFile(options.output, cliReference());
    return;
  }
  if (command === 'migrate-state') {
    requireValue(options.from && options.state, 'Pass --from and --state');
    const { migrateState } = await import('./control/migrate.js');
    return migrateState(options.from, options.state);
  }
  const target = options.config ?? 'hive-runners.lino';
  if (command === 'init') {
    const example = await readFile(
      new URL('./assets/config.example.lino', import.meta.url),
      'utf8'
    );
    const contents =
      extname(target).toLowerCase() === '.json'
        ? `${JSON.stringify(parseNotation(example), null, 2)}\n`
        : example;
    await writeFile(target, contents, { flag: 'wx', mode: 0o600 });
    return target;
  }
  if (command.startsWith('github-')) {
    return githubCommand(command, options, dependencies);
  }
  if (command.startsWith('gitlab-')) {
    return gitlabCommand(command, options, dependencies);
  }
  if (command.startsWith('account-')) {
    return accountCommand(command, options, dependencies);
  }
  const input = await loadConfig(target).catch((error) => {
    if (error.code === 'ENOENT' && !options.config) {
      return loadConfig('hive-runners.json');
    }
    throw error;
  });
  return runConfigured(command, options, input, dependencies);
}

export async function runHiveCli(
  argv,
  {
    env = process.env,
    fetcher,
    run,
    stdout = console.log,
    stderr = console.error,
  } = {}
) {
  const [command, ...args] = argv;
  try {
    if (!command || command === '--help' || command === '-h') {
      stdout(help());
      return 0;
    }
    if (command === '--version') {
      stdout(
        JSON.parse(
          await readFile(new URL('../package.json', import.meta.url), 'utf8')
        ).version
      );
      return 0;
    }
    requireValue(
      Object.hasOwn(commands, command),
      `Unknown command ${command}`
    );
    const { values: options } = parseArgs({
      args,
      options: { ...optionsByCommand[command], json: { type: 'boolean' } },
    });
    const result = await dispatch(command, options, { env, fetcher, run });
    if (result === undefined) {
      return 0;
    }
    stdout(
      typeof result === 'string'
        ? result
        : options.json
          ? JSON.stringify(result, null, 2)
          : formatNotation(result).trimEnd()
    );
    return 0;
  } catch (error) {
    stderr(error.message);
    return 1;
  }
}
