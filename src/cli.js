import { URL } from 'node:url';
import { readFile, writeFile } from 'node:fs/promises';
import { parseArgs } from 'node:util';
import {
  githubScope,
  loadConfig,
  match,
  requireValue,
  secret,
  slug,
} from './config.js';
import { githubClient } from './github.js';
import { deploy, renderInfrastructure } from './infrastructure.js';
import { propose } from './proposal.js';
import { providerClient } from './providers.js';

const commands = {
  init: ['[--config FILE]', 'Write an example runner configuration.'],
  render: [
    '[--config FILE] [--directory DIR]',
    'Write Terraform, Ansible and ARC files under hive-managed.',
  ],
  deploy: [
    '[--config FILE] (--inventory FILE | --apply-infra) [--directory DIR]',
    'Deploy ARC to SSH inventory hosts or explicitly apply Terraform first.',
  ],
  proposal: [
    '[--config FILE] [--base BRANCH] [--branch hive/NAME]',
    'Push an isolated configuration branch and open a draft pull request.',
  ],
  'github-runners': ['--scope ORG[/REPO]', 'List GitHub self-hosted runners.'],
  'github-groups': ['--scope ORG', 'List GitHub organization runner groups.'],
  'github-group': [
    '--scope ORG --name GROUP --repositories REPO[,REPO]',
    'Configure a runner group for selected private repositories.',
  ],
  'github-labels': [
    '--scope ORG[/REPO] --id RUNNER_ID --labels LABEL[,LABEL]',
    'Replace the custom labels on a directly registered runner.',
  ],
  'provider-list': [
    '--name PROVIDER [--config FILE]',
    'List compute instances through the configured provider API.',
  ],
  serve: [
    '[--config FILE]',
    'Start the fleet reconciler, landing page, and optional customer portal.',
  ],
  docs: [
    '[--output FILE]',
    'Generate the Markdown reference from this command registry.',
  ],
};

const optionsByCommand = Object.fromEntries(
  Object.entries(commands).map(([name, [usage]]) => [
    name,
    Object.fromEntries(
      [...usage.matchAll(/--([a-z-]+)/g)].map(([, option]) => [
        option,
        { type: option === 'apply-infra' ? 'boolean' : 'string' },
      ])
    ),
  ])
);

export function cliReference() {
  return [
    '# Hive Runners CLI reference',
    '',
    'Generated by `hive-runners docs`. Command options use the long forms below.',
    '',
    ...Object.entries(commands).flatMap(([name, [syntax, description]]) => [
      `## ${name}`,
      '',
      description,
      '',
      '```text',
      `hive-runners ${name} ${syntax}`,
      '```',
      '',
    ]),
  ].join('\n');
}

function help() {
  return [
    'Usage: hive-runners <command> [options]',
    '',
    ...Object.entries(commands).map(
      ([name, [syntax]]) => `  ${name} ${syntax}`
    ),
  ].join('\n');
}

function githubCommand(command, options, env, fetcher) {
  const scope = match(options.scope, githubScope, 'GitHub scope');
  const client = githubClient(secret('HIVE_GITHUB_TOKEN', env), fetcher);
  if (command === 'github-runners') {
    return client.listRunners(scope);
  }
  if (command === 'github-labels') {
    requireValue(
      typeof options.labels === 'string',
      'Pass --labels with comma-separated custom labels'
    );
    return client.setLabels(
      scope,
      Number(options.id),
      options.labels === ''
        ? []
        : options.labels
            .split(',')
            .map((label) =>
              match(label, /^[A-Za-z0-9][A-Za-z0-9._-]{0,99}$/, 'label')
            )
    );
  }
  requireValue(
    !scope.includes('/'),
    'Runner group commands require an organization scope'
  );
  if (command === 'github-groups') {
    return client.listGroups(scope);
  }
  return client.ensureGroup(
    scope,
    options.name,
    (options.repositories ?? '').split(',').filter(Boolean)
  );
}

async function runConfigured(command, options, input, { env, fetcher, run }) {
  if (command === 'render') {
    return renderInfrastructure(input, options.directory ?? '.');
  }
  if (command === 'deploy') {
    return deploy(input, {
      directory: options.directory,
      inventory:
        options.inventory &&
        JSON.parse(await readFile(options.inventory, 'utf8')),
      apply: options['apply-infra'] ?? false,
      env,
      run,
    });
  }
  if (command === 'proposal') {
    return propose(input, { base: options.base, branch: options.branch, run });
  }
  if (command === 'serve') {
    const { serve } = await import('./control/server.js');
    const server = await serve(input, { env });
    return `Hive Runners listening on port ${server.address().port}`;
  }
  const name = match(options.name, slug, 'provider name');
  requireValue(Object.hasOwn(input.providers, name), 'Provider not configured');
  return providerClient(input.providers[name], { env, fetcher }).list();
}

async function dispatch(command, options, dependencies) {
  if (command === 'docs') {
    if (!options.output) {
      return cliReference();
    }
    await writeFile(options.output, cliReference());
    return;
  }
  const target = options.config ?? 'hive-runners.json';
  if (command === 'init') {
    const example = await readFile(
      new URL('./assets/config.example.json', import.meta.url)
    );
    await writeFile(target, example, { flag: 'wx', mode: 0o600 });
    return target;
  }
  if (command.startsWith('github-')) {
    return githubCommand(
      command,
      options,
      dependencies.env,
      dependencies.fetcher
    );
  }
  return runConfigured(
    command,
    options,
    await loadConfig(target),
    dependencies
  );
}

export async function runHiveCli(
  argv,
  {
    env = process.env,
    fetcher,
    run,
    stdout = console.log,
    stderr = console.error,
  } = {}
) {
  const [command, ...args] = argv;
  try {
    if (!command || command === '--help' || command === '-h') {
      stdout(help());
      return 0;
    }
    if (command === '--version') {
      stdout(
        JSON.parse(
          await readFile(new URL('../package.json', import.meta.url), 'utf8')
        ).version
      );
      return 0;
    }
    requireValue(
      Object.hasOwn(commands, command),
      `Unknown command ${command}`
    );
    const { values: options } = parseArgs({
      args,
      options: optionsByCommand[command],
    });
    const result = await dispatch(command, options, { env, fetcher, run });
    if (result === undefined) {
      return 0;
    }
    stdout(
      typeof result === 'string' ? result : JSON.stringify(result, null, 2)
    );
    return 0;
  } catch (error) {
    stderr(error.message);
    return 1;
  }
}
